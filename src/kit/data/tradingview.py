"""TradingView chart exports: import the bars, and prove the Python ports match the TradingView indicators.

How to export (TradingView Plus or higher — https://www.tradingview.com/pricing/ "Data export"):
chart menu -> Export chart data -> pick "ISO time" or "UNIX timestamp". The file "includes time,
OHLC data, and any plots generated by your script" (TradingView Pine FAQ), so put the indicators
you want to check on the chart first. Export covers only the bars the chart shows
(Plus 10K, Premium 20K, Ultimate 40K bars).

Column names in the export are the plot titles; each indicator declares its own (tv_columns). Override with --map.
"""
from __future__ import annotations

import re
from pathlib import Path

import numpy as np
import pandas as pd

from ..config import TZ
from ..ind import compute as compute_all
from ..ind.tf import TF_SECONDS, norm_tf
from . import store

# Which TradingView plot titles match which port columns is declared by each indicator (tv_columns).


def _key(s: str) -> str:
    return re.sub(r"[^a-z0-9]", "", s.lower())


def read_csv(path: Path) -> pd.DataFrame:
    raw = pd.read_csv(path)
    cols = {c: c for c in raw.columns}
    tcol = next((c for c in raw.columns if _key(c) in ("time", "date", "datetime", "timestamp")), raw.columns[0])
    t = raw[tcol]
    if np.issubdtype(t.dtype, np.number):
        ts = pd.to_datetime(t, unit="s", utc=True)
    else:
        ts = pd.to_datetime(t, utc=True, format="mixed")
    df = pd.DataFrame({"ts_raw": ts.dt.tz_convert(TZ)})
    for want in ("open", "high", "low", "close"):
        c = next((c for c in raw.columns if _key(c) == want), None)
        if c is None:
            raise ValueError(f"{path.name}: no {want!r} column — is this a TradingView chart export?")
        df[want] = pd.to_numeric(raw[c], errors="coerce")
    vcol = next((c for c in raw.columns if _key(c) in ("volume", "vol")), None)
    df["volume"] = pd.to_numeric(raw[vcol], errors="coerce").fillna(0) if vcol else 0.0
    for c in raw.columns:
        if c not in cols or c == tcol or _key(c) in ("open", "high", "low", "close", "volume", "vol"):
            continue
        df["tv:" + c] = pd.to_numeric(raw[c], errors="coerce")
    return df


def guess_ticker(path: Path) -> str:
    """'BATS_MSFT, 60_1a2b3.csv' -> 'MSFT'. Pass --ticker when the file name says something else."""
    stem = Path(path).stem
    head = re.split(r"[,\s]", stem)[0]
    return head.split("_")[-1].upper() if "_" in head else head.upper()


def infer_tf(ts_open: pd.Series) -> str:
    """Bar spacing -> timeframe name (median gap within a day for intraday)."""
    d = ts_open.sort_values().diff().dropna().dt.total_seconds()
    if d.empty:
        raise ValueError("need at least two bars")
    intraday = d[d < 6 * 3600]
    if len(intraday) > len(d) * 0.5:
        g = float(intraday.median())
    else:
        g = float(d.median())
        if g >= 20 * 86400:
            return "1M"
        if g >= 5 * 86400:
            return "1W"
        return "1D"
    best = min((k for k, v in TF_SECONDS.items() if v < 86400), key=lambda k: abs(TF_SECONDS[k] - g))
    return best


def to_close_stamps(df: pd.DataFrame, tf: str) -> pd.DataFrame:
    """TradingView stamps bars at their OPEN; the kit uses CLOSE times."""
    out = df.copy()
    if TF_SECONDS[tf] < 86400:
        close = out["ts_raw"] + pd.to_timedelta(TF_SECONDS[tf], unit="s")
        day_end = out["ts_raw"].dt.normalize() + pd.Timedelta(hours=16)
        out["ts"] = close.where(close <= day_end, day_end)
    else:
        day = out["ts_raw"].dt.tz_localize(None).dt.normalize()
        if tf == "1W":     # TradingView stamps the week's first day; it closes Friday
            day = day + pd.to_timedelta((4 - day.dt.day_of_week) % 7, unit="D")
        elif tf in ("1M", "3M"):
            day = day + pd.offsets.BMonthEnd(0) if tf == "1M" else day + pd.offsets.BQuarterEnd(0)
        out["ts"] = (day + pd.Timedelta(hours=16)).dt.tz_localize(TZ)
    return out


def import_csv(path: Path, data_dir: Path, ticker: str | None = None, tf: str | None = None) -> dict:
    path = Path(path)
    df = read_csv(path)
    tf = norm_tf(tf) if tf else infer_tf(df["ts_raw"])
    ticker = ticker or guess_ticker(path)
    df = to_close_stamps(df, tf)
    dest = store.path(data_dir, tf, ticker).parent.parent.parent / "tv" / tf / f"{store.safe(ticker)}.parquet"
    dest.parent.mkdir(parents=True, exist_ok=True)
    df.to_parquet(dest, index=False)
    ind_cols = [c[3:] for c in df.columns if c.startswith("tv:")]
    return {"ticker": ticker, "tf": tf, "bars": len(df), "first": str(df.ts.min()), "last": str(df.ts.max()),
            "indicator_columns": ind_cols, "saved": str(dest)}


def _pick(df: pd.DataFrame, names: list[str]) -> str | None:
    want = [_key(n) for n in names]
    have = {_key(c[3:]): c for c in df.columns if c.startswith("tv:")}
    for w in want:
        if w in have:
            return have[w]
    return None


def match_check(path: Path, data_dir: Path, ticker: str | None = None, tf: str | None = None, mapping: dict | None = None,
                warmup: int = 300, ema_seed: str = "sma", top: int = 10, indicators: list[str] | None = None,
                tolerance: float = 0.5) -> dict:
    """Compare the Python ports (TradingView-replica mode) with the values in the export, bar by bar."""
    path = Path(path)
    df = read_csv(path)
    tf = norm_tf(tf) if tf else infer_tf(df["ts_raw"])
    ticker = ticker or guess_ticker(path)
    df = to_close_stamps(df, tf)
    bars = df[["ts", "open", "high", "low", "close", "volume"]].copy()
    # Prefer the kit's own (longer) store for warm-up and higher timeframes; else build from the CSV.
    stored = store.read(data_dir, tf, ticker)
    source = "csv"
    if stored is not None and len(stored) and stored.ts.min() <= bars.ts.min() and stored.ts.max() >= bars.ts.max() - pd.Timedelta(days=3):
        bars = stored[stored.ts <= bars.ts.max()].reset_index(drop=True)
        source = "store"

    def get(htf):
        s = store.read(data_dir, htf, ticker)
        if s is not None and len(s):
            return s
        # build it from the export's own bars (its warm-up will be shorter)
        if TF_SECONDS[norm_tf(htf)] < 86400:
            return store.resample_intraday(bars, htf)
        d = bars if TF_SECONDS[tf] >= 86400 else _daily_from_intraday(bars)
        return store.resample_daily(d, htf)

    from ..plugin import registry, resolve
    if not indicators:      # every indicator that declares TradingView columns found in this export
        from ..ind import DEFAULT_INDICATORS
        indicators = [n for n, i in registry().items()                      # every declared column must be present
                      if i.tv_columns and all(_pick(df, t) for t in i.tv_columns.values())] or DEFAULT_INDICATORS
    chosen = resolve(indicators)
    ind = compute_all(bars, tf, get, mode="tv", ema_seed=ema_seed, indicators=[i.name for i in chosen])
    j = df.merge(ind, on="ts", how="left", suffixes=("", "_port"))
    if source == "csv":
        j = j.iloc[warmup:].reset_index(drop=True)
    base_map = {col: titles for i in chosen for col, titles in i.tv_columns.items()}
    mapping = {**base_map, **{k: [v] for k, v in (mapping or {}).items()}}
    rows, worst = [], {}
    for port_col, names in mapping.items():
        tv_col = _pick(j, names)
        if tv_col is None or port_col not in j:
            rows.append({"reading": port_col, "tv_column": None, "bars": 0, "status": "not in export"})
            continue
        a, b = j[tv_col].to_numpy(float), j[port_col].to_numpy(float)
        ok = np.isfinite(a) & np.isfinite(b)
        diff = np.abs(a - b)[ok]
        tol = tolerance
        within = float((diff <= tol).mean()) if len(diff) else np.nan
        rows.append({"reading": port_col, "tv_column": tv_col[3:], "bars": int(ok.sum()),
                     "pct_within_tol": round(100 * within, 2) if len(diff) else None, "tolerance": tol,
                     "median_abs_diff": round(float(np.median(diff)), 4) if len(diff) else None,
                     "max_abs_diff": round(float(diff.max()), 4) if len(diff) else None,
                     "status": "MATCH" if len(diff) and within >= 0.98 else "CHECK"})
        if len(diff):
            jj = j.loc[ok, ["ts", tv_col, port_col]].copy()
            jj["abs_diff"] = np.abs(jj[tv_col] - jj[port_col])
            jj = jj.sort_values("abs_diff", ascending=False).head(top)
            worst[port_col] = [{"ts": str(r.ts), "tradingview": round(float(r[tv_col]), 4), "port": round(float(r[port_col]), 4),
                                "abs_diff": round(float(r.abs_diff), 4)} for _, r in jj.iterrows()]
    return {"ticker": ticker, "tf": tf, "bars_in_export": len(df), "warm_source": source,
            "indicators": {i.name: i.version for i in chosen},
            "warmup_skipped": warmup if source == "csv" else 0, "mode": "tv (TradingView replica)", "ema_seed": ema_seed,
            "table": rows, "worst": worst}


def _daily_from_intraday(bars: pd.DataFrame) -> pd.DataFrame:
    day = bars["ts"].dt.normalize()
    g = bars.assign(day=day).groupby("day")
    out = pd.DataFrame({"open": g["open"].first(), "high": g["high"].max(), "low": g["low"].min(),
                        "close": g["close"].last(), "volume": g["volume"].sum()}).reset_index()
    out["ts"] = out["day"] + pd.Timedelta(hours=16)
    return out[store.COLS]
